#!/usr/bin/env python3
"""Generates DrivePerfTokens.kt from docs/design/system/tokens.json (DRIVE-72).

Run from the repository root:  python3 apps/android/designsystem/tools/generate_tokens.py
The generated file is committed; tokens.json stays the source of truth.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[4]
TOKENS = json.loads((ROOT / "docs/design/system/tokens.json").read_text())
OUT = ROOT / "apps/android/designsystem/src/main/kotlin/com/driveperf/designsystem/DrivePerfTokens.kt"

M3_ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "error", "onError", "errorContainer", "onErrorContainer",
    "surface", "onSurface", "onSurfaceVariant", "inverseSurface", "inverseOnSurface",
    "outline", "outlineVariant", "scrim",
    "surfaceDim", "surfaceBright", "surfaceContainerLowest", "surfaceContainerLow",
    "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
    "primaryFixed", "primaryFixedDim", "onPrimaryFixed", "onPrimaryFixedVariant",
]
EXTENDED = [
    "warning", "warningContainer", "record", "onRecord", "recordContainer", "positive", "changeDown",
    "live", "liveGlow", "pro", "driveBg", "separator", "text2", "text3",
]


def argb(hex_value: str) -> str:
    h = hex_value.lstrip("#")
    if len(h) == 6:
        return "0xFF" + h.upper()
    return "0x" + h[6:8].upper() + h[0:6].upper()  # tokens carry alpha last (RRGGBBAA)


def color(hex_value: str) -> str:
    return f"Color({argb(hex_value)})"


def scheme(theme: str) -> str:
    m3 = TOKENS["color"]["m3"][theme]
    fn = "darkColorScheme" if theme == "dark" else "lightColorScheme"
    lines = [f"internal val DrivePerf{theme.capitalize()}ColorScheme: ColorScheme = {fn}("]
    for role in M3_ROLES:
        lines.append(f"    {role} = {color(m3[role])},")
    lines.append(f"    background = {color(m3['surface'])},")
    lines.append(f"    onBackground = {color(m3['onSurface'])},")
    lines.append(f"    surfaceVariant = {color(m3['surfaceContainerHighest'])},")
    lines.append(f"    surfaceTint = {color(m3['primary'])},")
    lines.append(")")
    return "\n".join(lines)


def data_class(name: str, fields: list[str], doc: str) -> str:
    body = ",\n".join(f"    public val {f}: Color" for f in fields)
    return f"/** {doc} */\n@Immutable\npublic data class {name}(\n{body},\n)"


def instance(name: str, cls: str, values: dict, fields: list[str]) -> str:
    body = "\n".join(f"    {f} = {color(values[f])}," for f in fields)
    return f"public val {name}: {cls} = {cls}(\n{body}\n)"


data_fields = [k for k in TOKENS["color"]["data"]["dark"] if k != "estimatedOpacity"]
out = [
    "// GENERATED by apps/android/designsystem/tools/generate_tokens.py from docs/design/system/tokens.json. Do not edit.",
    "package com.driveperf.designsystem",
    "",
    "import androidx.compose.material3.ColorScheme",
    "import androidx.compose.material3.darkColorScheme",
    "import androidx.compose.material3.lightColorScheme",
    "import androidx.compose.runtime.Immutable",
    "import androidx.compose.ui.graphics.Color",
    "",
    "// Material 3 colour roles (tokens.json color.m3). Seed #12B893, Night Drive neutrals.",
    scheme("dark"),
    "",
    scheme("light"),
    "",
    data_class("DpDataColors", data_fields,
               "Data colours (tokens.json color.data). Fixed per theme: they never follow dynamic colour."),
    "",
    instance("DarkDataColors", "DpDataColors", TOKENS["color"]["data"]["dark"], data_fields),
    "",
    instance("LightDataColors", "DpDataColors", TOKENS["color"]["data"]["light"], data_fields),
    "",
    data_class("DpExtendedColors", EXTENDED,
               "Semantic colours with no Material 3 role (tokens.json color.semantic.android)."),
    "",
    instance("DarkExtendedColors", "DpExtendedColors", TOKENS["color"]["semantic"]["android"]["dark"], EXTENDED),
    "",
    instance("LightExtendedColors", "DpExtendedColors", TOKENS["color"]["semantic"]["android"]["light"], EXTENDED),
    "",
]
OUT.write_text("\n".join(out))
print("wrote", OUT.relative_to(ROOT))
